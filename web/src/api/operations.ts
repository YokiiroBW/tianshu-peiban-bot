export async function callOperation<T>(
  path: string,
  body: object,
  csrf: string,
  signal: AbortSignal,
): Promise<T> {
  if (
    reads.has(path) ||
    /^models\/providers\/[^/]+\/models\/result$/.test(path)
  )
    return apiRead<T>(path, body, csrf, signal);
  if (
    !commands.has(path) &&
    !/^models\/(?:providers\/[^/]+\/(?:models|delete)|routes\/[^/]+\/(?:probe|delete))$/.test(
      path,
    )
  )
    throw new ApiError(
      "operation_not_registered",
      0,
      "此页面的操作尚未接入当前领域服务。",
    );
  if (!("client_request_id" in body) || !("expected_revision" in body))
    throw new ApiError(
      "command_identity_required",
      0,
      "请读取当前对象版本后再提交此操作。",
      null,
      null,
      "not_started",
    );
  return apiCommandData<T>(path, body as object & CommandInput, csrf, signal);
}

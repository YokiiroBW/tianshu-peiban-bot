def digest(value):
    return hashlib.sha256(json.dumps(wire(value), sort_keys=True, ensure_ascii=False,
                                     separators=(",", ":")).encode()).hexdigest()


def context_fingerprint(context):
    return digest({key: getattr(context, key) for key in
        ("actor_id", "person_id", "conversation_id", "scope_ids", "audience", "conversation_kind", "delivery_allowed")})


def submission_digest(request):
    """Identity of the caller's frozen request, before media and route adaptation."""
    value = wire(request)
    value["context"]["permissions"] = sorted(value["context"]["permissions"])
    value["required_capabilities"] = sorted(value["required_capabilities"])
    # Keep identities of requests accepted before these optional fields existed.
    if not value.get("behavior_refs"):
        value.pop("behavior_refs", None)
    for name in ("behavior_purpose", "data_generation"):
        if value.get(name) is None:
            value.pop(name, None)
    # For duration-based requests, the old budget deadline is not a business
    # deadline. It is regenerated by some callers and must not create new work.
    if request.execution_timeout_seconds is not None:
        value.pop("budget", None)
    return digest(value)


def receipt(row):
    usage = row.get("usage") or {}
    return ModelReceipt(
        row["attempt_id"], row["intent_id"], row["status"], row["dispatch"], row["route_id"],
        row["route_revision"], row["provider_id"], row["model"], row["protocol"],
        row["quota_group"], ModelUsage(**usage), row["provider_handle"], row["queued_at"],
        row["started_at"], row["finished_at"], row["first_output_ms"], row["error_code"], row.get("hold_until"), row.get("deadline_at"), row.get("execution_started_at"), row.get("cancellation_reason"), row.get("http_timing"), row.get("diagnostic"), row.get("wire_digest"), row.get("route_selection"),
        ({"recorded_events": row.get("recorded_events", 0), "truncated": row.get("stream_truncated", False),
          "upstream_complete": (row.get("diagnostic") or {}).get("category") == "complete"} if row.get("streaming") else None),
        row.get("submission_digest"), row.get("completion_digest"),
        str(row["data_generation"]) if row.get("data_generation") else None,
        row.get("completion_state"), row.get("completion_error_code"))


class AttemptLedger:
    def __init__(self, database, instance_id, *, statistics=None):
        self.database, self.instance_id = database, instance_id
        self.statistics = statistics
        self.statistics_failures = 0

    async def _record_statistics(self, connection, row):
        if self.statistics is None or row is None:
            return True
        from .statistics import attempt_event

        try:
            written = await self.statistics.record_safely_on(connection, attempt_event(row))
        except Exception:
            written = False
        if written is False:
            self.statistics_failures += 1
            try:
                async with connection.transaction():
                    await self.statistics.mark_producer_on(connection, "models", watermark=row["attempt_id"],
                        complete=False, detail={"reason": "attempt_statistics_pending"})
            except Exception:
                pass
            return False
        return True

    async def backfill_statistics(self, *, batch_size=200):
        """Rebuild replace-by-revision contributions from the actual attempt ledger."""
        if self.statistics is None:
            return {"complete": False, "reason": "statistics_not_bound"}
        if type(batch_size) is not int or batch_size < 1:
            raise ValueError("positive_statistics_batch_size_required")
        failures_at_start = self.statistics_failures
        cursor, complete, scanned = "", True, 0
        while True:
            async with self.database.transaction(control=True) as conn:
                rows = await (await conn.execute("SELECT * FROM models.attempts WHERE attempt_id>%s "
                    "ORDER BY attempt_id LIMIT %s", (cursor, batch_size))).fetchall()
                for row in rows:
                    complete = await self._record_statistics(conn, row) and complete
                    cursor = row["attempt_id"]
                    scanned += 1
                if len(rows) < batch_size:
                    complete = complete and failures_at_start == self.statistics_failures
                    await self.statistics.mark_producer_on(conn, "models", watermark=cursor,
                        complete=complete, detail={"scanned": scanned})
                    if complete and failures_at_start != self.statistics_failures:
                        complete = False
                        await self.statistics.mark_producer_on(conn, "models", watermark=cursor,
                            complete=False, detail={"reason": "concurrent_attempt_statistics_pending"})
                    return {"complete": complete, "watermark": cursor, "scanned": scanned}

    async def create(self, request, plan, units, *, frozen=None, streaming=False, completion=None,
                     input_estimate=None, data_generation=None):
        request_generation = getattr(request, "data_generation", None)
        if request_generation is not None and not isinstance(request_generation, str):
            raise AppError("model_data_generation_required", status=409)
        semantic = wire(request)
        semantic.pop("budget", None)
        if semantic.get("provider_session_scope") == "conversation":
            semantic.pop("provider_session_scope")
        if semantic.get("execution_start") == "admitted":
            semantic.pop("execution_start")
        if getattr(request, "execution_timeout_seconds", None) is None:
            semantic.pop("max_queue_wait", None)
        else:
            # Only the new contract canonicalizes unordered inputs. Existing
            # attempt digests retain their exact legacy representation.
            semantic["context"]["permissions"] = sorted(semantic["context"]["permissions"])
            if "required_capabilities" in semantic:
                semantic["required_capabilities"] = sorted(semantic["required_capabilities"])
        # New timing fields participate in a new attempt's identity. Omitting
        # absent fields preserves the digest of previously frozen attempts.
        for name in ("execution_timeout_seconds", "business_deadline_at"):
            if semantic.get(name) is None:
                semantic.pop(name, None)
        if not semantic.get("behavior_refs"):
            semantic.pop("behavior_refs", None)
        for name in ("behavior_purpose", "data_generation"):
            if semantic.get(name) is None:
                semantic.pop(name, None)
        request_hash = digest(semantic)
        queued_budget = waiting_budget(request)
        async with self.database.transaction(queued_budget) as conn:
            current_generation = await current_generation_on(conn)
            completion_generation = generation_id(completion.get("data_generation")) if completion is not None else None
            request_generation = generation_id(request_generation) if request_generation is not None else None
            expected_generation = (generation_id(data_generation) if data_generation is not None
                                   else request_generation or completion_generation or current_generation)
            if request_generation is not None:
                require_generation(request_generation, expected_generation)
            if completion_generation is not None:
                require_generation(completion_generation, expected_generation)
            require_generation(expected_generation, current_generation)
            cursor = await conn.execute(
                "INSERT INTO models.attempts(attempt_id,intent_id,principal_id,actor_id,"
                "conversation_id,function,service_class,route_id,route_revision,provider_id,"
                "model,protocol,quota_group,request_digest,status,dispatch,deadline_at,"
                "estimated_tokens,estimated_units,charged_units,broker_instance,billing_account,source_refs,context_fingerprint,persona_revision,"
                "execution_timeout_seconds,business_deadline_at,max_queue_wait,execution_start,provider_revision,estimated_input_tokens,data_generation) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,'queued','not_started',"
                "%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING RETURNING *",
                (request.attempt_id, request.intent_id, request.context.principal_id,
                 request.context.actor_id, request.context.conversation_id, request.function,
                 request.service_class.value, plan.route_id, plan.revision, plan.provider_id,
                 plan.model, plan.protocol, plan.quota_group, request_hash,
                 request.budget.deadline_at if getattr(request, "execution_timeout_seconds", None) is None else None,
                 units.get("tokens"), Jsonb(dict(units)),
                 Jsonb(dict(units)), self.instance_id, getattr(request, "billing_account", None),
                 Jsonb(wire(request.source_refs)), context_fingerprint(request.context), getattr(request, "persona_revision", None),
                 getattr(request, "execution_timeout_seconds", None), getattr(request, "business_deadline_at", None),
                 request.max_queue_wait, getattr(request, "execution_start", "admitted"), plan.provider_revision,
                 input_estimate, expected_generation))
            row = await cursor.fetchone()
            if row:
                if frozen is not None:
                    await conn.execute(
                        "INSERT INTO models.submissions(attempt_id,request_digest,request,streaming,completion,completion_digest,completion_state) "
                        "VALUES(%s,%s,%s,%s,%s,%s,%s)",
                        (request.attempt_id, submission_digest(frozen), Jsonb(wire(frozen)), streaming,
                         Jsonb(completion) if completion is not None else None,
                         digest(completion) if completion is not None else None,
                         "pending" if completion is not None else "none"))
                cancelled = await (await conn.execute("SELECT reason FROM models.cancellations "
                    "WHERE attempt_id=%s", (request.attempt_id,))).fetchone()
                if cancelled:
                    row = await (await conn.execute("UPDATE models.attempts SET status='cancelled',"
                        "cancel_requested=true,finished_at=now(),error_code=%s "
                        "WHERE attempt_id=%s RETURNING *", (
                            "consumer_interrupted" if cancelled["reason"] == "consumer_interrupted" else "cancelled_before_start",
                            request.attempt_id))).fetchone()
                await self._record_statistics(conn, row)
                return await self._cancellation(conn, row), True
            cursor = await conn.execute("SELECT * FROM models.attempts WHERE attempt_id=%s",
                                        (request.attempt_id,))
            row = await cursor.fetchone()
            if frozen is not None:
                saved = await (await conn.execute(
                    "SELECT * FROM models.submissions WHERE attempt_id=%s FOR UPDATE", (request.attempt_id,))).fetchone()
                if not saved or saved["request_digest"] != submission_digest(frozen):
                    raise AppError("attempt_identity_conflict", status=409)
                require_generation(row["data_generation"], expected_generation)
                await self._attach_completion(conn, saved, completion)
                return await self._cancellation(conn, row), False
            if row["request_digest"] != request_hash:
                raise AppError("attempt_identity_conflict", status=409)
            return await self._cancellation(conn, row), False

    async def claim_queued_submission(self, request):
        """Transfer only an unstarted frozen submission to this broker instance."""
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn)
            row = await (await conn.execute(
                "SELECT * FROM models.attempts WHERE attempt_id=%s FOR UPDATE",
                (request.attempt_id,))).fetchone()
            if row is None:
                raise AppError("attempt_not_found", status=404)
            saved = await (await conn.execute(
                "SELECT request_digest,request,recovery_state,recovery_wait,recovery_due_at,"
                "(recovery_due_at<=now()) AS recovery_due FROM models.submissions WHERE attempt_id=%s FOR UPDATE",
                (request.attempt_id,))).fetchone()
            if not saved or saved["request"] is None or saved["request_digest"] != submission_digest(request):
                raise AppError("attempt_identity_conflict", status=409)
            require_generation(row["data_generation"], current)
            if request.data_generation is not None:
                require_generation(request.data_generation, generation_id(row["data_generation"]))
            state = saved["recovery_state"]
            if state in {"checking", "observe_only"} or (state == "scheduled" and not saved["recovery_due"]):
                return await self._cancellation(conn, row), False, saved["request"]
            if state == "scheduled":
                from .recovery_wait import decode_wait, safely_retryable

                try:
                    valid_due = decode_wait(saved["recovery_wait"]).retry_at == saved["recovery_due_at"]
                except (TypeError, ValueError):
                    valid_due = False
                if not valid_due or not safely_retryable(saved["recovery_wait"]):
                    await conn.execute("UPDATE models.submissions SET recovery_state='observe_only' "
                                       "WHERE attempt_id=%s", (request.attempt_id,))
                    return await self._cancellation(conn, row), False, saved["request"]
            claimed = await (await conn.execute(
                "UPDATE models.attempts SET broker_instance=%s,revision=revision+1 "
                "WHERE attempt_id=%s AND status='queued' AND dispatch='not_started' "
                "AND NOT cancel_requested AND NOT EXISTS(SELECT 1 FROM models.cancellations c "
                "WHERE c.attempt_id=models.attempts.attempt_id) RETURNING *",
                (self.instance_id, request.attempt_id))).fetchone()
            if claimed is not None:
                await conn.execute("UPDATE models.submissions SET recovery_state='checking',"
                                   "recovery_due_at=NULL,recovery_wait=NULL WHERE attempt_id=%s",
                                   (request.attempt_id,))
            return await self._cancellation(conn, claimed or row), claimed is not None, saved["request"]

    async def prestart_check(self, attempt_id, *, active):
        """Fence dependency checks before they can leave ambiguous remote evidence."""
        async with self.database.transaction(control=True) as conn:
            row = await (await conn.execute(
                "SELECT status,dispatch,broker_instance,cancel_requested FROM models.attempts "
                "WHERE attempt_id=%s FOR UPDATE", (attempt_id,))).fetchone()
            if (not row or row["status"] != "queued" or row["dispatch"] != "not_started"
                    or row["broker_instance"] != self.instance_id or row["cancel_requested"]):
                raise AppError("attempt_owner_changed", status=409)
            if active:
                updated = await (await conn.execute(
                    "UPDATE models.submissions SET recovery_state='checking' "
                    "WHERE attempt_id=%s AND recovery_state IS NULL RETURNING attempt_id",
                    (attempt_id,))).fetchone()
            else:
                updated = await (await conn.execute(
                    "UPDATE models.submissions SET recovery_state=NULL "
                    "WHERE attempt_id=%s AND recovery_state='checking' RETURNING attempt_id",
                    (attempt_id,))).fetchone()
            if updated is None:
                raise AppError("model_prestart_observation_required", status=503,
                               details={"attempt_id": attempt_id, "action": "observe_original_attempt"})

    async def save_prestart_wait(self, attempt_id, wait):
        """Persist a wait only for this owner's original unstarted attempt."""
        from tianshu.runtime.recovery_policy import recovery_wait_retryable
        from .recovery_wait import encode_wait

        try:
            evidence = encode_wait(wait)
        except (TypeError, ValueError):
            evidence = None
        state = "scheduled" if evidence is not None and recovery_wait_retryable(wait) else "observe_only"
        due = wait.retry_at if evidence is not None else None
        async with self.database.transaction(control=True) as conn:
            row = await (await conn.execute(
                "SELECT status,dispatch,broker_instance,cancel_requested FROM models.attempts "
                "WHERE attempt_id=%s FOR UPDATE", (attempt_id,))).fetchone()
            if (not row or row["status"] != "queued" or row["dispatch"] != "not_started"
                    or row["broker_instance"] != self.instance_id or row["cancel_requested"]):
                return False
            updated = await (await conn.execute(
                "UPDATE models.submissions SET recovery_state=%s,recovery_due_at=%s,recovery_wait=%s "
                "WHERE attempt_id=%s AND (recovery_state IS NULL OR recovery_state='checking') RETURNING attempt_id",
                (state, due, Jsonb(evidence) if evidence is not None else None, attempt_id))).fetchone()
            return updated is not None

    @staticmethod
    async def _attach_completion(connection, saved, completion):
        if completion is None:
            return
        if saved["completion"] is not None and saved["completion"] != completion:
            raise AppError("model_completion_identity_conflict", status=409)
        if saved["completion"] is None:
            await connection.execute("UPDATE models.submissions SET completion=%s,completion_digest=%s,completion_state='pending',"
                                     "completion_error_code=NULL WHERE attempt_id=%s",
                                     (Jsonb(completion), digest(completion), saved["attempt_id"]))
            saved["completion_digest"] = digest(completion)
            saved["completion_state"] = "pending"

    async def existing_submission(self, request, completion=None):
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn) if completion is not None else None
            saved = await (await conn.execute(
                "SELECT s.*,a.data_generation,(s.recovery_due_at<=now()) AS recovery_due "
                "FROM models.submissions s JOIN models.attempts a USING(attempt_id) "
                "WHERE s.attempt_id=%s FOR UPDATE OF s", (request.attempt_id,))).fetchone()
            if not saved:
                return None
            if saved["request_digest"] != submission_digest(request):
                raise AppError("attempt_identity_conflict", status=409)
            if completion is not None:
                completion_generation = generation_id(completion.get("data_generation"))
                if request.data_generation is not None:
                    require_generation(request.data_generation, completion_generation)
                require_generation(completion_generation, current)
                require_generation(saved["data_generation"], completion_generation)
            await self._attach_completion(conn, saved, completion)
            row = await (await conn.execute("SELECT * FROM models.attempts WHERE attempt_id=%s",
                                            (request.attempt_id,))).fetchone()
            row = {**row, "submission_digest": saved["request_digest"],
                   "completion_digest": saved["completion_digest"],
                   "completion_state": saved["completion_state"],
                   "completion_error_code": saved["completion_error_code"],
                   "recovery_state": saved["recovery_state"], "recovery_wait": saved["recovery_wait"],
                   "recovery_due_at": saved["recovery_due_at"], "recovery_due": saved["recovery_due"]}
            return await self._cancellation(conn, row), saved["streaming"]

    async def pending_submissions(self):
        async with self.database.transaction(control=True, read_only=True) as conn:
            return await (await conn.execute(
                "SELECT s.request,s.streaming,a.queued_at FROM models.submissions s "
                "JOIN models.attempts a USING(attempt_id) "
                "WHERE a.status='queued' AND a.dispatch='not_started' AND NOT a.cancel_requested AND s.request IS NOT NULL "
                "AND (s.recovery_state IS NULL OR (s.recovery_state='scheduled' AND s.recovery_due_at<=now())) "
                "ORDER BY a.queued_at,a.attempt_id")).fetchall()

    async def wakeable_submissions(self, *, after=None, limit=100):
        async with self.database.transaction(control=True, read_only=True) as conn:
            return await (await conn.execute(
                "SELECT s.attempt_id,s.request,s.streaming,COALESCE(s.recovery_due_at,a.queued_at) AS wake_at "
                "FROM models.submissions s "
                "JOIN models.attempts a USING(attempt_id) WHERE a.status='queued' AND a.dispatch='not_started' "
                "AND NOT a.cancel_requested AND s.request IS NOT NULL AND "
                "((s.recovery_state='scheduled' AND s.recovery_due_at<=now()) OR "
                "(s.recovery_state IS NULL AND a.broker_instance IS DISTINCT FROM %s)) "
                "AND (%s::timestamptz IS NULL OR "
                "(COALESCE(s.recovery_due_at,a.queued_at),s.attempt_id)>(%s::timestamptz,%s)) "
                "ORDER BY COALESCE(s.recovery_due_at,a.queued_at),s.attempt_id LIMIT %s",
                (self.instance_id, after[0] if after else None, after[0] if after else None,
                 after[1] if after else "", limit))).fetchall()

    async def expire_stale_recovery_submissions(self):
        """A scheduled old-generation request cannot be resumed after a cutover."""
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn)
            rows = await (await conn.execute(
                "UPDATE models.attempts a SET status='cancelled',finished_at=now(),revision=revision+1,"
                "error_code='data_generation_expired' FROM models.submissions s "
                "WHERE s.attempt_id=a.attempt_id AND s.recovery_state='scheduled' "
                "AND a.status='queued' AND a.dispatch='not_started' "
                "AND NOT a.cancel_requested AND NOT EXISTS (SELECT 1 FROM models.cancellations c "
                "WHERE c.attempt_id=a.attempt_id) "
                "AND a.data_generation IS DISTINCT FROM %s RETURNING a.*", (current,))).fetchall()
            for row in rows:
                await self._record_statistics(conn, row)

    async def block_invalid_recovery(self, attempt_id):
        async with self.database.transaction(control=True) as conn:
            row = await (await conn.execute("SELECT status,dispatch FROM models.attempts "
                "WHERE attempt_id=%s FOR UPDATE", (attempt_id,))).fetchone()
            if not row or row["status"] != "queued" or row["dispatch"] != "not_started":
                return
            await conn.execute("UPDATE models.submissions SET recovery_state='observe_only' "
                "WHERE attempt_id=%s AND (recovery_state IS NULL OR recovery_state='scheduled')", (attempt_id,))

    async def append_event(self, attempt_id, event, *, validate):
        async with self.database.transaction(control=True) as conn:
            if not await validate(conn):
                raise AppError("result_source_unavailable", status=403)
            await conn.execute("INSERT INTO models.stream_events(attempt_id,event) VALUES(%s,%s)",
                               (attempt_id, Jsonb(wire(event))))

    async def stream_events(self, attempt_id, after):
        async with self.database.transaction(control=True, read_only=True) as conn:
            return await (await conn.execute(
                "SELECT sequence,event FROM models.stream_events WHERE attempt_id=%s AND sequence>%s "
                "ORDER BY sequence LIMIT 128", (attempt_id, after))).fetchall()

    async def truncate_stream(self, attempt_id):
        async with self.database.transaction(control=True) as conn:
            await conn.execute("UPDATE models.submissions SET stream_truncated=true WHERE attempt_id=%s", (attempt_id,))

    async def save_observation(self, attempt_id, *, timing=None, diagnostic=None):
        async with self.database.transaction(control=True) as conn:
            await conn.execute("UPDATE models.attempts SET http_timing=COALESCE(%s,http_timing),"
                "diagnostic=COALESCE(%s,diagnostic),revision=revision+1 WHERE attempt_id=%s",
                (Jsonb(timing) if timing is not None else None,
                 Jsonb(diagnostic) if diagnostic is not None else None, attempt_id))

    async def cooldowns(self):
        async with self.database.transaction(control=True, read_only=True) as conn:
            return await (await conn.execute(
                "SELECT quota_group,blocked_until FROM models.quota_cooldowns WHERE blocked_until>now()" )).fetchall()

    async def defer_quota(self, group, until):
        async with self.database.transaction(control=True) as conn:
            await conn.execute("INSERT INTO models.quota_cooldowns(quota_group,blocked_until,reason) "
                "VALUES(%s,%s,'retry_after') ON CONFLICT(quota_group) DO UPDATE "
                "SET blocked_until=GREATEST(models.quota_cooldowns.blocked_until,excluded.blocked_until),"
                "reason=excluded.reason,updated_at=now()", (group, until))

    async def route_cooldowns(self):
        async with self.database.transaction(control=True, read_only=True) as conn:
            return await (await conn.execute("SELECT c.route_id,c.blocked_until,r.quota_group "
                "FROM models.route_cooldowns c JOIN models.routes r USING(route_id) WHERE c.blocked_until>now()")).fetchall()

    async def defer_route(self, route_id, until):
        async with self.database.transaction(control=True) as conn:
            await conn.execute("INSERT INTO models.route_cooldowns(route_id,blocked_until,reason) "
                "VALUES(%s,%s,'upstream_unavailable') ON CONFLICT(route_id) DO UPDATE "
                "SET blocked_until=GREATEST(models.route_cooldowns.blocked_until,excluded.blocked_until),"
                "reason=excluded.reason,updated_at=now()", (route_id, until))

    async def record_wire(self, attempt_id, wire_digest, selection):
        async with self.database.transaction(control=True) as conn:
            row = await (await conn.execute(
                "UPDATE models.attempts SET wire_digest=%s,route_selection=COALESCE(route_selection,%s),"
                "revision=revision+1 WHERE attempt_id=%s AND status='queued' AND broker_instance=%s "
                "AND (wire_digest IS NULL OR wire_digest=%s) RETURNING attempt_id",
                (wire_digest, Jsonb(selection), attempt_id, self.instance_id, wire_digest))).fetchone()
            if not row:
                raise AppError("model_wire_changed_before_execution", status=409)

    async def get(self, attempt_id):
        async with self.database.transaction(control=True, read_only=True) as conn:
            cursor = await conn.execute("SELECT a.*,c.reason AS cancellation_reason,s.streaming,s.stream_truncated,"
                                        "s.recovery_state,s.recovery_due_at,s.recovery_wait,"
                                        "(s.recovery_due_at<=now()) AS recovery_due,"
                                        "s.request_digest AS submission_digest,s.completion_digest,"
                                        "s.completion_state,s.completion_error_code,"
                                        "(SELECT count(*) FROM models.stream_events e WHERE e.attempt_id=a.attempt_id) AS recorded_events "
                                        "FROM models.attempts a LEFT JOIN models.cancellations c USING(attempt_id) "
                                        "LEFT JOIN models.submissions s USING(attempt_id) WHERE a.attempt_id=%s",
                                        (attempt_id,))
            return await cursor.fetchone()

    @staticmethod
    async def _cancellation(connection, row):
        if row is None:
            return None
        cancelled = await (await connection.execute("SELECT reason FROM models.cancellations WHERE attempt_id=%s",
            (row["attempt_id"],))).fetchone()
        return {**row, "cancellation_reason": cancelled["reason"] if cancelled else None}

    async def assert_generation(self, attempt_id):
        """Recheck the attempt's frozen generation immediately before dispatch."""
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn)
            original = await (await conn.execute(
                "SELECT data_generation FROM models.attempts WHERE attempt_id=%s", (attempt_id,))).fetchone()
            if not original:
                raise AppError("attempt_not_found", status=404)
            require_generation(original["data_generation"], current)

    async def admitted(self, attempt_id, deadline_at):
        """External admission starts its execution window, without claiming I/O."""
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn)
            original = await (await conn.execute("SELECT data_generation FROM models.attempts "
                "WHERE attempt_id=%s FOR UPDATE", (attempt_id,))).fetchone()
            if not original:
                raise AppError("attempt_cancelled_before_start", status=409)
            require_generation(original["data_generation"], current)
            row = await (await conn.execute("UPDATE models.attempts SET deadline_at=%s,execution_started_at=now(),revision=revision+1 "
                "WHERE attempt_id=%s AND status='queued' AND NOT cancel_requested "
                "AND deadline_at IS NULL AND execution_timeout_seconds IS NOT NULL AND %s>now() "
                "AND NOT EXISTS(SELECT 1 FROM models.cancellations c "
                "WHERE c.attempt_id=models.attempts.attempt_id) RETURNING *",
                (deadline_at, attempt_id, deadline_at))).fetchone()
        if not row:
            raise AppError("attempt_cancelled_before_start", status=409)
        return row

    async def started(self, attempt_id, hold_seconds, *, deadline_at=None):
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn)
            original = await (await conn.execute("SELECT data_generation,broker_instance FROM models.attempts "
                "WHERE attempt_id=%s FOR UPDATE", (attempt_id,))).fetchone()
            if not original:
                raise AppError("attempt_cancelled_before_start", status=409)
            require_generation(original["data_generation"], current)
            if original["broker_instance"] != self.instance_id:
                raise AppError("attempt_owner_changed", status=409)
            submission = await (await conn.execute(
                "SELECT recovery_state FROM models.submissions WHERE attempt_id=%s FOR UPDATE",
                (attempt_id,))).fetchone()
            if submission and submission["recovery_state"] in {"scheduled", "observe_only"}:
                raise AppError("model_prestart_observation_required", status=503,
                               details={"attempt_id": attempt_id, "action": "observe_original_attempt"})
            cursor = await conn.execute(
                "UPDATE models.attempts SET status='running',dispatch='submitted',started_at=now(),"
                "execution_started_at=CASE WHEN execution_start='admitted' THEN COALESCE(execution_started_at,now()) ELSE execution_started_at END,"
                "deadline_at=COALESCE(%s,deadline_at),"
                "hold_until=CASE WHEN %s::double precision IS NULL THEN NULL ELSE "
                "GREATEST(COALESCE(%s,deadline_at),now()+(%s*interval '1 second')) END,"
                "charged_tokens=estimated_tokens,revision=revision+1 "
                "WHERE attempt_id=%s AND broker_instance=%s AND status='queued' AND NOT cancel_requested "
                "AND (COALESCE(%s,deadline_at)>now() OR (execution_start='provider_running' "
                "AND deadline_at IS NULL AND (business_deadline_at IS NULL OR business_deadline_at>now()))) "
                "AND NOT EXISTS(SELECT 1 FROM models.cancellations c "
                "WHERE c.attempt_id=models.attempts.attempt_id) RETURNING *",
                (deadline_at, hold_seconds, deadline_at, hold_seconds, attempt_id, self.instance_id, deadline_at))
            row = await cursor.fetchone()
            if not row:
                raise AppError("attempt_cancelled_before_start", status=409)
            if submission and submission["recovery_state"] == "checking":
                await conn.execute("UPDATE models.submissions SET recovery_state=NULL WHERE attempt_id=%s",
                                   (attempt_id,))
            await self._record_statistics(conn, row)
            return row

    async def observe_external(self, attempt_id, provider_handle, state, *, hold_seconds=None, validate_observation):
        async with self.database.transaction(control=True) as conn:
            # Preserve the Sources -> Models lock order used by withdrawal.
            if not await validate_observation(conn):
                raise AppError("source_unavailable", status=403)
            row = await (await conn.execute("SELECT * FROM models.attempts "
                "WHERE attempt_id=%s FOR UPDATE", (attempt_id,))).fetchone()
            if not row or row["protocol"] != "external":
                raise AppError("external_attempt_not_found", status=404)
            if row["provider_handle"] != provider_handle or not row["started_at"] or row["dispatch"] == "not_started":
                raise AppError("external_provider_handle_changed", status=409)
            if row["execution_start"] != "provider_running":
                return await self._cancellation(conn, row)
            # Use the execution owner's clock, after lock waiting has finished.
            # PostgreSQL now() is its transaction-start clock and can also live
            # on another host from the Broker/Client timeout machinery.
            observed_at = datetime.now(UTC)
            started, deadline, hold = row["execution_started_at"], row["deadline_at"], row["hold_until"]
            if started is None and state in {"running", "completed"}:
                started = observed_at
                deadline = started + timedelta(seconds=row["execution_timeout_seconds"])
                if row["business_deadline_at"] is not None:
                    deadline = min(deadline, row["business_deadline_at"])
                if hold_seconds is not None and row["status"] == "running":
                    hold = max(value for value in (hold, deadline, started + timedelta(seconds=hold_seconds))
                        if value is not None)
            updated = await (await conn.execute("UPDATE models.attempts SET provider_state=%s,provider_observed_at=%s,"
                "execution_started_at=%s,deadline_at=%s,hold_until=%s,revision=revision+1 WHERE attempt_id=%s RETURNING *",
                (state, observed_at, started, deadline, hold, attempt_id))).fetchone()
            return await self._cancellation(conn, updated)

    async def observe_usage(self, attempt_id, provider_handle, usage, *, validate_observation):
        """Amend metering only; a late usage report never settles an unknown result."""
        async with self.database.transaction(control=True) as conn:
            if not await validate_observation(conn):
                raise AppError("source_unavailable", status=403)
            row = await (await conn.execute("SELECT * FROM models.attempts WHERE attempt_id=%s FOR UPDATE",
                                             (attempt_id,))).fetchone()
            if not row:
                raise AppError("attempt_not_found", status=404)
            if not provider_handle or row["provider_handle"] != provider_handle or row["dispatch"] == "not_started":
                raise AppError("model_usage_handle_mismatch", status=409)
            previous = row.get("usage") or {}
            value = {**previous, **{key: item for key, item in wire(usage).items()
                                    if item is not None and key != "estimated_input_tokens"}}
            if previous == value:
                return await self._cancellation(conn, row)
            tokens = (value["input_tokens"] + value["output_tokens"]
                      if value.get("input_tokens") is not None and value.get("output_tokens") is not None else None)
            row = await (await conn.execute(
                "UPDATE models.attempts SET usage=%s,charged_tokens=COALESCE(%s,charged_tokens),"
                "charged_units=CASE WHEN %s::bigint IS NULL THEN charged_units ELSE "
                "jsonb_set(charged_units,'{tokens}',to_jsonb(%s::bigint),true) END,revision=revision+1 "
                "WHERE attempt_id=%s RETURNING *", (Jsonb(value), tokens, tokens, tokens, attempt_id))).fetchone()
            await self._record_statistics(conn, row)
            return await self._cancellation(conn, row)

    async def checkpoint(self, attempt_id, *, provider_handle=None, first_output_ms=None, output_observed=True):
        async with self.database.transaction(control=True) as conn:
            await conn.execute(
                "UPDATE models.attempts SET output_observed=output_observed OR %s,provider_handle=COALESCE(%s,"
                "provider_handle),first_output_ms=COALESCE(first_output_ms,%s),revision=revision+1 "
                "WHERE attempt_id=%s", (output_observed, provider_handle, first_output_ms, attempt_id))

    async def finish(self, attempt_id, status, *, usage=None, result=None, error_code=None,
                     charged_units=None, provider_handle=None, validate_result=None, dispatch=None):
        async with self.database.transaction(control=True) as conn:
            if result is not None and validate_result is not None and not await validate_result(conn):
                result = None
                error_code = error_code or "result_source_unavailable"
            cursor = await conn.execute(
                "UPDATE models.attempts SET status=%s,dispatch=COALESCE(%s,CASE WHEN %s='unknown' "
                "THEN 'unknown' ELSE dispatch END),finished_at=now(),usage=%s,result=%s,error_code=%s,"
                "provider_handle=COALESCE(%s,provider_handle),charged_units=COALESCE(%s,charged_units),"
                "charged_tokens=COALESCE(%s,charged_tokens),revision=revision+1 "
                "WHERE attempt_id=%s AND status NOT IN ('succeeded','failed','cancelled') RETURNING *",
                (status, dispatch, status, Jsonb(wire(usage)) if usage is not None else None,
                 Jsonb(wire(result)) if result is not None else None, error_code, provider_handle,
                 Jsonb(dict(charged_units)) if charged_units is not None else None,
                 charged_units.get("tokens") if charged_units else None, attempt_id))
            row = await cursor.fetchone()
            if row is None:
                row = await (await conn.execute("SELECT * FROM models.attempts WHERE attempt_id=%s", (attempt_id,))).fetchone()
            else:
                await self._record_statistics(conn, row)
            return await self._cancellation(conn, row)

    async def finish_before_start(self, attempt_id, status, *, error_code=None, timing=None, diagnostic=None):
        """Settle preparation failure only while this broker still owns the queue."""
        if status not in {"failed", "cancelled"}:
            raise ValueError("invalid_prestart_status")
        async with self.database.transaction(control=True) as conn:
            row = await (await conn.execute(
                "UPDATE models.attempts SET status=%s,finished_at=now(),error_code=%s,"
                "http_timing=COALESCE(%s,http_timing),diagnostic=COALESCE(%s,diagnostic),revision=revision+1 "
                "WHERE attempt_id=%s AND broker_instance=%s AND status='queued' AND dispatch='not_started' "
                "AND (NOT cancel_requested OR %s='cancelled') RETURNING *",
                (status, error_code, Jsonb(timing) if timing is not None else None,
                 Jsonb(diagnostic) if diagnostic is not None else None,
                 attempt_id, self.instance_id, status))).fetchone()
            if row is None:
                return None
            await self._record_statistics(conn, row)
            return await self._cancellation(conn, row)

    async def request_cancel(self, attempt_id, *, reason="explicit_cancel", expected_owner=None):
        if reason not in {"explicit_cancel", "consumer_interrupted"}:
            raise AppError("invalid_model_cancellation_reason")
        async with self.database.transaction(control=True) as conn:
            # Lock in the same order for explicit and owner-scoped cancellation.
            owner = await (await conn.execute(
                "SELECT broker_instance FROM models.attempts WHERE attempt_id=%s FOR UPDATE",
                (attempt_id,))).fetchone()
            if expected_owner is not None and (owner is None or owner["broker_instance"] != expected_owner):
                return None
            await conn.execute("INSERT INTO models.cancellations AS c(attempt_id,reason) VALUES(%s,%s) "
                "ON CONFLICT(attempt_id) DO UPDATE SET reason=CASE WHEN c.reason='explicit_cancel' "
                "THEN c.reason ELSE excluded.reason END", (attempt_id, reason))
            cursor = await conn.execute(
                "UPDATE models.attempts SET cancel_requested=true,revision=revision+1 "
                "WHERE attempt_id=%s RETURNING *", (attempt_id,))
            return await self._cancellation(conn, await cursor.fetchone())

    async def recover(self):
        async with self.database.transaction(control=True) as conn:
            current = await current_generation_on(conn)
            cancelled = await (await conn.execute("UPDATE models.attempts a SET status='cancelled',finished_at=now(),revision=revision+1,"
                "error_code='cancelled_before_start' WHERE status='queued' AND "
                "(cancel_requested OR EXISTS (SELECT 1 FROM models.cancellations c WHERE c.attempt_id=a.attempt_id)) RETURNING *")).fetchall()
            for row in cancelled:
                await self._record_statistics(conn, row)
            expired = await (await conn.execute("UPDATE models.attempts a SET status='cancelled',finished_at=now(),"
                "revision=revision+1,error_code='data_generation_expired' WHERE status='queued' "
                "AND data_generation IS DISTINCT FROM %s RETURNING *", (current,))).fetchall()
            for row in expired:
                await self._record_statistics(conn, row)
            abandoned = await (await conn.execute("UPDATE models.attempts a SET status='cancelled',finished_at=now(),revision=revision+1,"
                "error_code='broker_restarted_before_start' WHERE status='queued' "
                "AND NOT EXISTS (SELECT 1 FROM models.submissions s WHERE s.attempt_id=a.attempt_id "
                "AND s.request IS NOT NULL) RETURNING *")).fetchall()
            for row in abandoned:
                await self._record_statistics(conn, row)
            unknown = await (await conn.execute("UPDATE models.attempts SET status='unknown',dispatch='unknown',"
                "finished_at=now(),error_code='broker_restarted_after_submit',revision=revision+1 WHERE status='running' RETURNING *")).fetchall()
            for row in unknown:
                await self._record_statistics(conn, row)
            await conn.execute("UPDATE models.submissions s SET completion_state='expired',"
                "completion_error_code='data_generation_expired' FROM models.attempts a "
                "WHERE a.attempt_id=s.attempt_id AND s.completion_state='pending' AND "
                "(a.data_generation IS DISTINCT FROM %s OR "
                "COALESCE(lower(s.completion->>'data_generation'),'')<>%s)", (current, str(current)))
            cursor = await conn.execute(
                "SELECT * FROM models.attempts WHERE started_at>now()-interval '60 seconds' "
                "OR (status='unknown' AND hold_until>now())")
            return await cursor.fetchall()


async def purge_source_results(connection, source_ref):
    """Source owner calls this in its forgetting transaction, through the models port."""
    await purge_source_results_many(connection, (source_ref,))


async def purge_source_results_many(connection, source_refs):
    if not source_refs:
        return
    rows = await (await connection.execute("SELECT a.attempt_id FROM models.attempts a WHERE a.attempt_id IN ("
        "SELECT c.attempt_id FROM unnest(%s::text[],%s::bigint[]) s(source_id,revision) JOIN models.attempts c "
        "ON c.source_refs @> jsonb_build_array(jsonb_build_object('source_id',s.source_id,'revision',s.revision))) "
        "ORDER BY a.attempt_id FOR UPDATE", ([ref.source_id for ref in source_refs],
                                            [ref.revision for ref in source_refs]))).fetchall()
    if rows:
        await connection.execute("UPDATE models.attempts SET result=NULL,revision=revision+1 WHERE attempt_id=ANY(%s)",
                                  ([row["attempt_id"] for row in rows],))
        await connection.execute("UPDATE models.submissions SET request=NULL WHERE attempt_id=ANY(%s)",
                                 ([row["attempt_id"] for row in rows],))
        await connection.execute("DELETE FROM models.stream_events WHERE attempt_id=ANY(%s)",
                                 ([row["attempt_id"] for row in rows],))

"""The model port used by all domains, in-process or across the broker boundary."""

from collections.abc import AsyncIterator
from typing import Literal, Protocol
from tianshu.types import TrustedContext

from .types import ExternalRequest, ModelEvent, ModelReceipt, ModelRequest, ModelResult, ModelUsage
from tianshu.runtime.jobs import JobSpec


class ModelPort(Protocol):
    async def submit(self, request: ModelRequest, *, completion: JobSpec | None = None) -> ModelReceipt: ...
    async def generate(self, request: ModelRequest) -> ModelResult: ...
    def stream(self, request: ModelRequest) -> AsyncIterator[ModelEvent]: ...
    async def cancel(self, attempt_id: str, *, reason: str = "explicit_cancel") -> ModelReceipt | None: ...
    async def status(self, attempt_id: str, *,
                     phase: Literal["pre_submit", "observe"] = "observe") -> ModelReceipt | None: ...
    async def require_receipt(self, attempt_id: str) -> ModelReceipt: ...
    async def result(self, attempt_id: str, *, context: TrustedContext) -> ModelResult | None: ...
    async def reusable_result(self, attempt_id: str, *, context: TrustedContext,
                              expected_request_digest: str | None = None,
                              expected_data_generation: str | None = None) -> ModelResult: ...
    async def observe_external(self, attempt_id: str, *, context: TrustedContext,
                               provider_handle: str, state: str) -> ModelReceipt: ...
    async def observe_usage(self, attempt_id: str, *, context: TrustedContext,
                            provider_handle: str, usage: ModelUsage) -> ModelReceipt: ...
    def resource(self, request: ExternalRequest): ...
    async def embedding_profile(self) -> dict: ...
    async def generation_profile(self, request: ModelRequest) -> dict: ...
